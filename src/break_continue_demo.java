void main() {
    // Break
    for (int i = 1; i <= 10; i++) {
        if (i == 9) {
            break;

        }

        System.out.println(i);
    }

    //continue
    for (int i = 1; i <= 10; i++) {
        if (i == 6) {
            continue;
        }
        System.out.println(i);

    }
    // while loop
    int i = 10;
    while (i <= 20) {
        System.out.println(i);
        i++;
    }
}
